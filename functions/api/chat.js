export async function onRequestPost(context) {
  const { request, env } = context;

  try {
    const body = await request.json();

    // ぼたんの人格を使うかどうか。
    //   通常のチャット → SYSTEM（＋その人の記憶メモ）を付ける
    //   記憶の要約など persona:false の呼び出し → 人格は付けない
    let systemPrompt;
    if (body.persona === false) {
      systemPrompt = body.system || undefined;
    } else {
      const note = (body.memoryNote || '').trim();
      systemPrompt = SYSTEM + (note ? `

【この人について覚えていること】
${note}

※これは前に話したことのメモ。知っていて当たり前のこととして、自然に会話に混ぜる。
　わざわざ読み上げたり、「記憶によると」のような言い方はしない。` : '');
    }

    const payload = {
      model: body.model || 'claude-sonnet-4-20250514',
      max_tokens: body.max_tokens || 1000,
      messages: body.messages
    };
    if (systemPrompt) payload.system = systemPrompt;

    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': env.ANTHROPIC_API_KEY,
        'anthropic-version': '2023-06-01'
      },
      body: JSON.stringify(payload)
    });

    const data = await response.json();

    return new Response(JSON.stringify(data), {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type'
      }
    });
  } catch(e) {
    return new Response(JSON.stringify({ error: e.message }), {
      status: 500,
      headers: {
        'Content-Type': 'application/json',
        'Access-Control-Allow-Origin': '*'
      }
    });
  }
}

export async function onRequestOptions() {
  return new Response(null, {
    status: 204,
    headers: {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type'
    }
  });
}
